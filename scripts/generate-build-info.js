#!/usr/bin/env node
/**
 * Writes src/shared/buildInfo.js with the manifest version, git commit, branch,
 * dirty flag and build time so the running extension can identify itself.
 *
 * Runs automatically before `npm run dev`, `start`, `build:*` and `lint`, and
 * from build.sh. The output file is git-ignored.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'src/manifest.json'), 'utf8'));

function git(args, fallback = 'unknown') {
  try {
    return execSync(`git ${args}`, { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return fallback;
  }
}

const info = {
  version: manifest.version,
  commit: git('rev-parse --short HEAD'),
  branch: git('rev-parse --abbrev-ref HEAD'),
  dirty: git('status --porcelain', '') !== '',
  builtAt: new Date().toISOString()
};

const out = path.join(root, 'src/shared/buildInfo.js');
const body = `// Generated by scripts/generate-build-info.js. Do not edit; do not commit.
window.QuadTVBuild = Object.freeze(${JSON.stringify(info, null, 2)});
`;
fs.writeFileSync(out, body);
console.log(`Build info: v${info.version} ${info.branch}@${info.commit}${info.dirty ? ' (dirty)' : ''} ${info.builtAt}`);
